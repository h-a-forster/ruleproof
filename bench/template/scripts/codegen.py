"""Generate src/invoicing/generated/ from spec/invoicing.toml.

Usage:
    uv run python scripts/codegen.py          # rewrite the generated modules
    uv run python scripts/codegen.py --check  # exit 1 if they are out of date
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "invoicing.toml"
OUT = ROOT / "src" / "invoicing" / "generated"

HEADER = "# Generated by scripts/codegen.py from spec/invoicing.toml. Do not edit by hand.\n"


def q(text: str) -> str:
    """A double-quoted Python string literal."""
    return json.dumps(text, ensure_ascii=False)


def render_currencies(spec: dict) -> str:
    lines = [
        HEADER,
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class Currency(NamedTuple):",
        "    code: str",
        "    name: str",
        "    symbol: str",
        "    decimals: int",
        "",
        "",
        "CURRENCIES: dict[str, Currency] = {",
    ]
    for code in sorted(spec["currencies"]):
        c = spec["currencies"][code]
        decimals = int(c["decimals"])
        if not 0 <= decimals <= 4:
            raise SystemExit(f"{code}: decimals must be between 0 and 4")
        lines.append(
            f"    {q(code)}: Currency({q(code)}, {q(c['name'])}, {q(c['symbol'])}, {decimals}),"
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_tax_rates(spec: dict) -> str:
    lines = [
        HEADER,
        "from __future__ import annotations",
        "",
        "from decimal import Decimal",
        "",
        "TAX_RATES: dict[str, Decimal] = {",
    ]
    for name in sorted(spec["tax_rates"]):
        rate = Decimal(str(spec["tax_rates"][name]))
        if not Decimal(0) <= rate < Decimal(1):
            raise SystemExit(f"tax rate {name}: must be in [0, 1)")
        lines.append(f"    {q(name)}: Decimal({q(str(rate))}),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_init() -> str:
    return (
        HEADER
        + '"""Tables generated from spec/invoicing.toml."""\n\n'
        + "from invoicing.generated.currencies import CURRENCIES, Currency\n"
        + "from invoicing.generated.tax_rates import TAX_RATES\n\n"
        + '__all__ = ["CURRENCIES", "TAX_RATES", "Currency"]\n'
    )


def outputs(spec: dict) -> dict[Path, str]:
    return {
        OUT / "__init__.py": render_init(),
        OUT / "currencies.py": render_currencies(spec),
        OUT / "tax_rates.py": render_tax_rates(spec),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if files are out of date")
    args = parser.parse_args(argv)

    with SPEC.open("rb") as f:
        spec = tomllib.load(f)

    stale = []
    for path, text in outputs(spec).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")

    if args.check and stale:
        sys.stderr.write("out of date: " + ", ".join(stale) + "\n")
        return 1
    for name in stale:
        sys.stdout.write(f"wrote {name}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
